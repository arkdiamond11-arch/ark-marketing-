/* ---------------- the translator ---------------- */
let I18N_PREFIX = null;     // first word → multi-word keys (longest first)
const I18N_SEPS = [' · ', ' — ', '. ', ': ', ', ', '; '];
const I18N_EDGE = /^([^\p{L}]*)([\s\S]*?)([^\p{L}]*)$/u;
const I18N_MISSES = new Set();

function i18nPrefixIndex() {
  if (I18N_PREFIX) return I18N_PREFIX;
  I18N_PREFIX = new Map();
  Object.keys(I18N).forEach((k) => {
    const sp = k.indexOf(' ');
    if (sp < 1) return;
    const w = k.slice(0, sp);
    if (!I18N_PREFIX.has(w)) I18N_PREFIX.set(w, []);
    I18N_PREFIX.get(w).push(k);
  });
  I18N_PREFIX.forEach((list) => list.sort((a, b) => b.length - a.length));
  return I18N_PREFIX;
}

function trText(s) {
  if (LANG === 'en' || !s) return s;
  const m = I18N_EDGE.exec(s);
  if (!m || !m[2]) return s;
  const t = trCore(m[2]);
  return t == null ? s : m[1] + t + m[3];
}

function trCore(core) {
  const i = LANG === 'hi' ? 0 : 1;
  const e = I18N[core];
  if (e) return e[i];
  for (let k = 0; k < I18N_RX.length; k++) {
    const r = I18N_RX[k], mm = r[0].exec(core);
    if (mm) {
      return r[i + 1].replace(/([$%])(\d)/g, (_, kind, n) => {
        const g = mm[+n] || '';
        return kind === '%' ? trText(g) : g;
      });
    }
  }
  // pieces joined by " · " or " — ", then "words (more words)", then sentences / lists
  for (let k = 0; k < I18N_SEPS.length; k++) {
    if (k === 2) {
      const pm = /^(.+?) \((.+)$/.exec(core);
      if (pm) { const a = trText(pm[1]), b = trText(pm[2]); if (a !== pm[1] || b !== pm[2]) return a + ' (' + b; }
    }
    const sep = I18N_SEPS[k];
    if (core.indexOf(sep) < 0) continue;
    const parts = core.split(sep);
    let changed = false;
    const out = parts.map((p) => { const t = trText(p); if (t !== p) changed = true; return t; });
    if (changed) return out.join(sep);
  }
  // a known phrase of 2+ words followed by something we can also translate
  const sp = core.indexOf(' ');
  if (sp > 0) {
    const list = i18nPrefixIndex().get(core.slice(0, sp));
    if (list) {
      for (let k = 0; k < list.length; k++) {
        const key = list[k];
        if (core.length > key.length + 1 && core.startsWith(key + ' ')) {
          const rest = core.slice(key.length + 1);
          const rt = trText(rest);
          if (rt !== rest || !/\p{L}/u.test(rest)) return I18N[key][i] + ' ' + rt;
        }
      }
    }
  }
  if (window.I18N_DEBUG && /[A-Za-z]{2}/.test(core) && !/[\u0900-\u0AFF]/.test(core)) I18N_MISSES.add(core);
  return null;
}

/* ---------------- applying it to the screen ---------------- */
const I18N_SKIP_TAGS = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, CODE: 1, PRE: 1 };
let I18N_OBS = null;

function i18nSkipEl(el) {
  return I18N_SKIP_TAGS[el.tagName] === 1 || (el.classList && el.classList.contains('noi18n')) || el.isContentEditable;
}
function i18nAttrs(el) {
  if (el.nodeType !== 1) return;
  for (const a of ['placeholder', 'title', 'aria-label']) {
    const v = el.getAttribute(a);
    if (v && /[A-Za-z]/.test(v)) { const t = trText(v); if (t !== v) el.setAttribute(a, t); }
  }
  // keep a select's chosen value in English even though its label changes
  if (el.tagName === 'OPTION' && !el.hasAttribute('value')) el.setAttribute('value', el.textContent);
}
function i18nTextNode(n) {
  const v = n.nodeValue;
  if (!v || !/[A-Za-z]/.test(v)) return;
  const t = trText(v);
  if (t !== v) n.nodeValue = t;
}
function i18nNode(n) {
  if (LANG === 'en' || !n) return;
  if (n.nodeType === 3) {
    const p = n.parentElement;
    if (!p || p.closest('script,style,textarea,code,pre,.noi18n,[contenteditable="true"]')) return;
    i18nTextNode(n);
    return;
  }
  if (n.nodeType !== 1) return;
  if (n.closest('script,style,textarea,code,pre,.noi18n,[contenteditable="true"]')) return;
  const w = document.createTreeWalker(n, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
    acceptNode: (x) => {
      if (x.nodeType !== 1 || !i18nSkipEl(x)) return NodeFilter.FILTER_ACCEPT;
      if (x.tagName === 'TEXTAREA' && !x.classList.contains('noi18n')) i18nAttrs(x);   // its hint, never what was typed
      return NodeFilter.FILTER_REJECT;
    },
  });
  let x = w.currentNode;
  while (x) {
    if (x.nodeType === 3) i18nTextNode(x); else i18nAttrs(x);
    x = w.nextNode();
  }
}

function i18nStart() {
  if (LANG === 'en' || I18N_OBS || !document.body) return;
  i18nNode(document.body);
  I18N_OBS = new MutationObserver((muts) => {
    if (LANG === 'en') return;
    for (let k = 0; k < muts.length; k++) {
      const mu = muts[k];
      if (mu.type === 'characterData') i18nNode(mu.target);
      else if (mu.type === 'attributes') { if (!mu.target.closest('.noi18n')) i18nAttrs(mu.target); }
      else mu.addedNodes.forEach(i18nNode);
    }
  });
  I18N_OBS.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] });
}

function i18nApply(code) {
  LANG = code;
  document.documentElement.lang = code;
  if (code === 'en') { if (I18N_OBS) { I18N_OBS.disconnect(); I18N_OBS = null; } return; }
  if (I18N_OBS) i18nNode(document.body); else i18nStart();
}

/* ---------------- choosing a language ---------------- */
function renderLangPicker() {
  const c = document.getElementById('content');
  if (!c) return;
  c.innerHTML =
    '<div class="hint" style="margin:2px 2px 12px">Choose the language for the app screens.</div>' +
    LANG_LIST.map((l) => '<button class="lang-opt noi18n' + (l[0] === LANG ? ' on' : '') + '" data-action="lang-set" data-lang="' + l[0] + '">' +
      '<span>' + l[1] + (l[2] ? ' <small style="font-weight:500;color:var(--muted)">' + l[2] + '</small>' : '') + '</span>' +
      (l[0] === LANG ? '<span>✓</span>' : '') + '</button>').join('') +
    '<div class="notice">PDFs, WhatsApp messages and Excel exports stay in English. Type client names and addresses in English letters so they print correctly on PDFs.</div>';
}

function setLang(code) {
  if (!LANG_LIST.some((l) => l[0] === code)) return;
  try { localStorage.setItem('lang', code); } catch (e) { /* private mode */ }
  i18nApply(code);
  if (typeof S !== 'undefined' && S.me) {
    S.me.lang = code;
    db.from('profiles').update({ lang: code }).eq('id', S.me.id).then(() => {}, () => {});
  }
  if (typeof S !== 'undefined' && S.sub && S.sub.length) { S.suppressPop = true; try { history.back(); } catch (e) { /* ignore */ } }
  if (typeof S !== 'undefined') S.sub = [];
  renderShell();
  switchTab('more');
  toast(code === 'hi' ? 'भाषा: हिन्दी ✓' : code === 'gu' ? 'ભાષા: ગુજરાતી ✓' : 'Language: English ✓', 'ok');
}

window.ACTIONS['lang-open'] = () => showSub('Language', renderLangPicker);
window.ACTIONS['lang-set'] = (el) => setLang(el.dataset.lang);

